-- V2: endurecimento da autenticação (R16.9, R17.2 a R17.5)

-- 1. Colunas novas em USUARIOS (usuários existentes recebem TOKEN_VERSION = 0)
ALTER TABLE USUARIOS ADD COLUMN TOKEN_VERSION   INTEGER   NOT NULL DEFAULT 0;
ALTER TABLE USUARIOS ADD COLUMN ULTIMO_LOGIN_EM TIMESTAMP NULL;

-- 2. Refresh tokens (somente o hash é persistido)
CREATE TABLE REFRESH_TOKENS (
    ID                 UUID         NOT NULL,
    USUARIO_ID         UUID         NOT NULL,
    TOKEN_HASH         VARCHAR(64)  NOT NULL,
    FAMILIA_ID         UUID         NOT NULL,
    EXPIRA_EM          TIMESTAMP    NOT NULL,
    REVOGADO_EM        TIMESTAMP    NULL,
    MOTIVO_REVOGACAO   VARCHAR(30)  NULL,
    SUBSTITUIDO_POR_ID UUID         NULL,
    CRIADO_EM          TIMESTAMP    NOT NULL,
    USER_AGENT         VARCHAR(255) NULL,
    IP                 VARCHAR(45)  NULL,
    CONSTRAINT PK_REFRESH_TOKENS PRIMARY KEY (ID),
    CONSTRAINT UK_REFRESH_TOKENS_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_REFRESH_TOKENS_USUARIO FOREIGN KEY (USUARIO_ID)
        REFERENCES USUARIOS (ID) ON DELETE CASCADE
);
-- UK_REFRESH_TOKENS_HASH já cria o índice único usado na busca por hash.
CREATE INDEX IDX_REFRESH_TOKENS_USUARIO ON REFRESH_TOKENS (USUARIO_ID);
CREATE INDEX IDX_REFRESH_TOKENS_FAMILIA ON REFRESH_TOKENS (FAMILIA_ID);

-- 3. Trilha de auditoria de segurança (sem FK para USUARIOS: o histórico sobrevive à exclusão)
CREATE TABLE EVENTOS_SEGURANCA (
    ID         UUID         NOT NULL,
    TIPO       VARCHAR(40)  NOT NULL,
    USUARIO_ID UUID         NULL,
    INSTANTE   TIMESTAMP    NOT NULL,
    IP         VARCHAR(45)  NULL,
    DETALHE    VARCHAR(500) NULL,
    CONSTRAINT PK_EVENTOS_SEGURANCA PRIMARY KEY (ID)
);
CREATE INDEX IDX_EVENTOS_SEGURANCA_USUARIO  ON EVENTOS_SEGURANCA (USUARIO_ID);
CREATE INDEX IDX_EVENTOS_SEGURANCA_INSTANTE ON EVENTOS_SEGURANCA (INSTANTE);
